import { EvaluatedRequest, ConflictResolutionResult } from './types.js';
import { AlternativeSlot } from '../types/index.js';

/**
 * Generates an articulate, transparent, natural-language explanation
 * describing the reasoning, fairness metrics, and trade-offs of the scheduling allocation.
 */
export function generateSchedulingExplanation(
  winner: EvaluatedRequest,
  losers: EvaluatedRequest[],
  equipmentName: string,
  alternativesForLosers: Record<string, AlternativeSlot[]>
): string {
  const winnerReq = winner.request;
  const winnerBreakdown = winner.breakdown;
  const winDeadlineStr = new Date(winnerReq.projectDeadline).toLocaleDateString();

  let explanation = `### 🧠 AI Scheduling Recommendation Summary\n\n`;
  explanation += `**Allocated Student:** ${winnerReq.student.name} (${winnerReq.project.title})\n`;
  explanation += `**Resource:** ${equipmentName}\n`;
  explanation += `**Composite Priority Score:** ${winnerBreakdown.totalScore}/100\n\n`;

  explanation += `#### 📊 Decision Rationale & Scoring Breakdown:\n`;
  explanation += `1. **Project Deadline Urgency (${winnerBreakdown.deadlineUrgency}/100 - Weight: 35%):** ` +
    `The project "${winnerReq.project.title}" faces a critical deadline on ${winDeadlineStr}. ` +
    `Immediate lab access is vital to ensure timely experimental validation before milestone submission.\n`;

  explanation += `2. **Technical Compatibility (${winnerBreakdown.compatibility}/100 - Weight: 25%):** ` +
    `The project's architectural requirements (${winnerReq.technicalRequirements || winnerReq.project.category}) ` +
    `closely align with ${equipmentName}'s hardware capabilities (${winnerReq.equipment.specifications.slice(0, 80)}...).\n`;

  explanation += `3. **Historical Allocation Fairness (${winnerBreakdown.fairness}/100 - Weight: 15%):** ` +
    `To prevent resource monopolization, ${winnerReq.student.name} was evaluated based on their current booking history. ` +
    `With ${winnerReq.student.bookings ? winnerReq.student.bookings.length : 0} prior approved sessions, ` +
    `allocating this slot maintains campus-wide equitable access.\n`;

  explanation += `4. **Waiting Time (${winnerBreakdown.waitingTime}/100 - Weight: 15%):** ` +
    `Request has been queued and evaluated through the automated fairness buffer.\n`;

  explanation += `5. **Scheduling Feasibility (${winnerBreakdown.feasibility}/100 - Weight: 10%):** ` +
    `Requested duration (${winnerReq.durationMinutes / 60} hrs) fits within standard lab operating hours (08:00 - 18:00) ` +
    `and satisfies equipment safety thresholds.\n\n`;

  if (losers.length > 0) {
    explanation += `#### ⚖️ Competing Request Comparison & Mitigations:\n`;
    for (const loser of losers) {
      const loserReq = loser.request;
      const loserScore = loser.breakdown.totalScore;
      const loserAlternatives = alternativesForLosers[loserReq.id] || [];

      explanation += `- **${loserReq.student.name}** ("${loserReq.project.title}") scored **${loserScore}/100**. `;
      if (loser.breakdown.deadlineUrgency < winnerBreakdown.deadlineUrgency) {
        explanation += `Their project deadline is further out (${new Date(loserReq.projectDeadline).toLocaleDateString()}), `;
      }
      if (loser.breakdown.fairness < winnerBreakdown.fairness) {
        explanation += `and they have utilized more lab hours previously. `;
      }
      explanation += `\n`;

      if (loserAlternatives.length > 0) {
        explanation += `  - *Suggested Viable Alternatives:* `;
        const altDescriptions = loserAlternatives.map(alt => 
          alt.type === 'SLOT' 
            ? `Same equipment on ${alt.date} at ${alt.startTime}-${alt.endTime}` 
            : `${alt.equipmentName} (${alt.departmentName}) on ${alt.date} at ${alt.startTime}`
        );
        explanation += `${altDescriptions.join('; ')}.\n`;
      }
    }
  }

  explanation += `\n*Recommendation generated by LabLink Deterministic Fair Allocation Engine.*`;

  return explanation;
}
